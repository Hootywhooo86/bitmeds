"""Regenerates SpriteData.java (icon grids + fixed palette) from app/pixelart.js.
Run from the repo root:  python3 android/tools/gen_sprites.py"""
import re
src = open('app/pixelart.js').read()
block = src[src.index('var SPR = {'):src.index('// syringe: f = filled')]
grids = {}
for m in re.finditer(r'(\w+):\s*\[(.*?)\]', block, re.S):
    rows = re.findall(r'"([^"]+)"', m.group(2))
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (m.group(1), [len(r) for r in rows])
    grids[m.group(1)] = rows
pal = dict(re.findall(r"(\w):'(#[0-9a-f]{6})'", src[src.index('var PAL'):src.index('var SPR')]))
g = "\n".join(f'        G.put("{k}", new String[]{{\n            ' + ",\n            ".join(f'"{r}"' for r in v) + "});" for k, v in grids.items())
p = "\n".join(f"            case '{k}': return 0x{v[1:].upper()};" for k, v in pal.items())
open('android/app/src/main/java/com/bitmeds/app/SpriteData.java', 'w').write(f'''package com.bitmeds.app;

import java.util.HashMap;
import java.util.Map;

/** GENERATED by android/tools/gen_sprites.py from app/pixelart.js — do not edit by hand. */
final class SpriteData {{
    static final Map<String, String[]> G = new HashMap<>();
    static {{
{g}
    }}

    /** Fixed palette colour as 0xRRGGBB, or -1 for transparent / med-colour chars (A, a, L). */
    static int pal(char c) {{
        switch (c) {{
{p}
            default: return -1;
        }}
    }}
}}
''')
print(len(grids), 'icons,', len(pal), 'colours')
